CATEGORIES = ('Продукты','Транспорт','Связь','Быт','Другое')

def budget(profile, expenses):
 total=profile.budget; mandatory=profile.mandatory; reserve=profile.reserve
 allocations={k:Decimal(str(profile.allocations.get(k, 0))) for k in CATEGORIES}
 planned=sum(allocations.values(),Decimal('0'))
 available=total-mandatory-reserve
 spent=sum((e.amount for e in expenses),Decimal('0'))
 spent_by_category={k:sum((e.amount for e in expenses if e.category==k),Decimal('0')) for k in CATEGORIES}
 return {'budget':total,'mandatory':mandatory,'reserve':reserve,'allocations':allocations,'planned':planned,'unallocated':available-planned,'spent_by_category':spent_by_category,'spent':spent,'remaining':total-mandatory-spent,'warning':mandatory+reserve+planned>total}

