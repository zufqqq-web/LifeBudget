def generate(profile):
 products={p.name:p for p in Product.objects.all()}
 excluded=[]
 for raw in (profile.allergies+','+profile.preferences).split(','):
  word=raw.strip().lower()
  if not word: continue
  normalized=word.replace('‘','').replace('’','').replace("'",'').replace('ʻ','').replace('ʼ','')
  aliases=ALLERGEN_ALIASES.get(normalized) or ALLERGEN_ALIASES.get(word)
  if aliases: excluded.extend(aliases)
  elif any(word in name.lower() for name in products): excluded.append(word)
  else: raise ValueError('Не удалось распознать ограничение: '+word+'. Укажите конкретный ингредиент из каталога.')
 groups={}
 for recipe in RECIPES:
  name,kind,minutes,ingredients,steps=recipe
  text=' '.join([name]+[i[0] for i in ingredients]).lower()
  if any(x in text for x in excluded): continue
  if all(i[0] in products for i in ingredients): groups.setdefault(kind,[]).append(recipe)
 if any(not groups.get(k) for k in ['Завтрак','Обед','Ужин']): raise ValueError('Не удалось подобрать полное меню с указанными ограничениями. Уточните аллергию или предпочтения.')
 meals=[]; shopping=Counter()
 for day in range(1,31):
  for kind in ['Завтрак','Обед','Ужин']:
   name,_,minutes,ingredients,steps=groups[kind][(day-1)%len(groups[kind])]
   items=[]; cost=Decimal('0')
   for product_name,quantity in ingredients:
    p=products[product_name]; q=round(quantity*profile.household,2); cost+=p.price*Decimal(str(q))
    items.append({'name':product_name,'quantity':q,'unit':p.unit,'price':float(p.price)})
    if day<=7: shopping[product_name]+=q
   meals.append({'day':day,'kind':kind,'name':name,'minutes':minutes,'ingredients':items,'steps':steps,'cost':round(float(cost),2)})
 return meals,[{'name':name,'quantity':round(q,2),'unit':products[name].unit,'category':products[name].category,'price':float(products[name].price),'checked':False} for name,q in shopping.items()]
